// The CA service owns ALL behavioural data — no shared DB with the demo app or any other service.
// Keystroke samples/events, per-user typing profiles, mouse profiles/samples, the decision logs, the
// escalation state and locks, the training queue and the study tables live here, keyed by an opaque
// userId. It stores no users, passwords, passkeys or sessions.
//
// STORAGE picks the backend:
//   sqlite    (default) one file (DB_PATH), as before: one copy of the service
//   postgres  DATABASE_URL: ca-service's own database, so several copies can run side by side
// Both behind ONE async interface:
//   await db.get(sql, ...params)    one row or undefined
//   await db.all(sql, ...params)    rows
//   await db.run(sql, ...params)    { changes }
//   await db.insert(sql, ...params) the new row's id (tables with an `id`)
//   await db.tx(async () => ...)    a transaction: every db call made inside it, by any module, runs on
//                                   the transaction's connection (AsyncLocalStorage), so nothing slips out
// SQL is written once, SQLite-style with ? placeholders. The postgres backend translates the few
// differences (placeholders, the timestamp functions, camelCase result names), and keeps every value in
// the SAME text format as SQLite (timestamps "YYYY-MM-DD HH:MM:SS", JSON as text, 0/1 flags), so stored
// data reads back unchanged and past decisions replay identically.
