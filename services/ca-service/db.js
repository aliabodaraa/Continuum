// Columns added after their table first existed (SQLite files made before them get them on open).
const ADDED_COLUMNS = [
  ["keystroke_texts", "text_hash", "TEXT"], ["keystroke_texts", "char_count", "INTEGER"],
  ["mouse_profiles", "threshold", "REAL"], ["mouse_profiles", "feature_version", "TEXT"],
  ["mouse_profiles", "enrol_percentiles", "TEXT"], ["mouse_profiles", "loso_percentiles", "TEXT"],
  ["mouse_profiles", "decision_version", "TEXT"],
  ["study_decisions", "details", "TEXT"], ["study_decisions", "client", "TEXT"],
  ["training_jobs", "locked_by", "TEXT"], ["training_jobs", "lease_until", "TEXT"],
];
const SQL_TYPES = {
  sqlite: { ID: "INTEGER PRIMARY KEY AUTOINCREMENT", USERID: "INTEGER", BIGINTEGER: "INTEGER", INT: "INTEGER", REAL: "REAL", NOWTEXT: "DATETIME DEFAULT CURRENT_TIMESTAMP" },
  // user ids are up to 2^52 (bigint); REAL is a 64-bit float in both; timestamps stay TEXT in SQLite's format
  postgres: { ID: "bigserial PRIMARY KEY", USERID: "bigint", BIGINTEGER: "bigint", INT: "bigint", REAL: "double precision",
    NOWTEXT: "text DEFAULT to_char(now() at time zone 'utc', 'YYYY-MM-DD HH24:MI:SS')" },
};
function createTableSql(kind, name, cols) {
  const t = SQL_TYPES[kind];
  const body = cols.replace(/--[^\n]*\n/g, "\n").replace(/\b(ID|USERID|BIGINTEGER|INT|REAL|NOWTEXT)\b/g, (m) => t[m]);
  return `CREATE TABLE IF NOT EXISTS ${name} (${body})`;
}

// ---------------------------------------------------------------- the two backends
const als = new AsyncLocalStorage();   // { conn } inside db.tx()

function sqliteBackend(file) {
  const Database = require("better-sqlite3");
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const s = new Database(file);
  for (const [name, cols] of TABLES) s.exec(createTableSql("sqlite", name, cols));
  // Additive migration for files made before a column existed, so an old file ends up with the same
  // shape as a new one.
  for (const [name, col, decl] of ADDED_COLUMNS) {
    const have = s.prepare(`PRAGMA table_info(${name})`).all().map((c) => c.name);
    if (have.length && !have.includes(col)) s.exec(`ALTER TABLE ${name} ADD COLUMN ${col} ${decl}`);
  }
  for (const ix of INDEXES) {
    try { s.exec(ix); } catch (e) { console.error(`[db] ${ix.split(" ON ")[0]}: ${e.message}`); }
  }
  const cache = new Map();
  const st = (sql) => {
    let p = cache.get(sql);
    if (!p) { if (cache.size > 500) cache.clear(); p = s.prepare(sql); cache.set(sql, p); }
    return p;
  };
  const direct = {
    get: async (sql, params) => st(sql).get(...params),
    all: async (sql, params) => st(sql).all(...params),
    run: async (sql, params) => ({ changes: st(sql).run(...params).changes }),
    insert: async (sql, params) => Number(st(sql).run(...params).lastInsertRowid),
    exec: async (sql) => s.exec(sql),
  };
  // One connection: a transaction holds it, and a call from OUTSIDE it waits until it ends, so it can
  // never run inside it (with an await inside a transaction it otherwise could). The check and the
  // statement run with no await between them, so no transaction can open in the gap.
  let active = false, busy = Promise.resolve();
  const gate = (f) => async (sql, params) => { while (active) await busy; return f(sql, params); };
  const conn = { get: gate(direct.get), all: gate(direct.all), run: gate(direct.run), insert: gate(direct.insert), exec: gate(direct.exec) };
  return {
    kind: "sqlite",
    raw: s,
    conn,
    async tx(fn) {
      while (active) await busy;
      active = true;
      let release;
      busy = new Promise((r) => (release = r));
      try {
        s.exec("BEGIN IMMEDIATE");
        const out = await als.run({ conn: direct }, fn);
        s.exec("COMMIT");
        return out;
      } catch (e) {
        try { if (s.inTransaction) s.exec("ROLLBACK"); } catch (_) {}
        throw e;
      } finally { active = false; release(); }
    },
    async ready() { s.prepare("SELECT 1").get(); },
    async close() { s.close(); },
  };
}

// SQLite-style SQL -> PostgreSQL. Cached per statement text.
const NOW_TEXT = "to_char(now() at time zone 'utc', 'YYYY-MM-DD HH24:MI:SS')";
const pgSqlCache = new Map();
function toPg(sql) {
  let out = pgSqlCache.get(sql);
  if (out) return out;
  let n = 0;
  out = sql
    .replace(/'(?:[^']|'')*'|\?/g, (m) => (m === "?" ? "$" + ++n : m))       // placeholders, not inside quotes
    .replace(/\bCURRENT_TIMESTAMP\b/g, NOW_TEXT)
    .replace(/datetime\('now'\)/g, NOW_TEXT)
    .replace(/\bAS\s+([a-z]+[A-Z][A-Za-z0-9]*)\b/g, 'AS "$1"');           // keep camelCase result names
  if (pgSqlCache.size > 2000) pgSqlCache.clear();
  pgSqlCache.set(sql, out);
  return out;
}

async function postgresBackend(url) {
  let pg;
  try { pg = require("pg"); } catch (e) { throw new Error("STORAGE=postgres needs the 'pg' package (the image has it)"); }
  if (!url) throw new Error("STORAGE=postgres needs DATABASE_URL (postgres://user:password@host:5432/db)");
  // bigint and numeric as JS numbers (ids, counts and sums here stay far below 2^53), like SQLite
  const types = new pg.TypeOverrides();
  types.setTypeParser(20, (v) => (v === null ? null : Number(v)));
  types.setTypeParser(1700, (v) => (v === null ? null : Number(v)));
  const pool = new pg.Pool({ connectionString: url, max: Number(process.env.DATABASE_POOL_MAX || 10), types });
  pool.on("error", (e) => console.error(`[db] idle database connection failed: ${e.message}`));
  const c = await pool.connect();
  try {
    await c.query("BEGIN");
    await c.query("SELECT pg_advisory_xact_lock(4100417)");   // copies starting together create the schema once
    for (const [name, cols] of TABLES) await c.query(createTableSql("postgres", name, cols));
    for (const ix of INDEXES) await c.query(ix);
    await c.query("COMMIT");
  } catch (e) { await c.query("ROLLBACK").catch(() => {}); throw e; } finally { c.release(); }

  const on = (client) => ({
    get: async (sql, params) => (await client.query(toPg(sql), params)).rows[0],
    all: async (sql, params) => (await client.query(toPg(sql), params)).rows,
    run: async (sql, params) => ({ changes: (await client.query(toPg(sql), params)).rowCount }),
    insert: async (sql, params) => Number((await client.query(toPg(sql) + " RETURNING id", params)).rows[0].id),
    exec: async (sql) => client.query(sql),
  });
  return {
    kind: "postgres",
    pool,
    conn: on(pool),
    async tx(fn) {
      const client = await pool.connect();
      try {
        await client.query("BEGIN");
        const out = await als.run({ conn: on(client) }, fn);
        await client.query("COMMIT");
        return out;
      } catch (e) {
        await client.query("ROLLBACK").catch(() => {});
        throw e;
      } finally { client.release(); }
    },
    async ready() { await pool.query("SELECT 1"); },
    async close() { await pool.end(); },
  };
}

// ---------------------------------------------------------------- the module's interface
let backend = null, opening = null;
function open() {
  if (backend) return Promise.resolve(backend);
  if (!opening) {
    opening = (async () => {
      if (STORAGE === "sqlite") backend = sqliteBackend(process.env.DB_PATH ? path.resolve(process.env.DB_PATH) : path.resolve(__dirname, "ca.db"));
      else if (STORAGE === "postgres") backend = await postgresBackend(process.env.DATABASE_URL);
      else throw new Error(`STORAGE must be sqlite or postgres (got ${process.env.STORAGE})`);
      return backend;
    })().catch((e) => { opening = null; throw e; });   // a failed attempt is not kept: the next open() tries again
  }
  return opening;
}
// The connection for this call: the transaction's, inside db.tx(); otherwise the shared one (SQLite's
// waits out any transaction another request holds).
async function conn() {
  const inTx = als.getStore();
  if (inTx) return inTx.conn;
  return (await open()).conn;
}

const db = {
  open,
  get kind() { return backend ? backend.kind : STORAGE; },
  get: async (sql, ...params) => (await conn()).get(sql, params),
  all: async (sql, ...params) => (await conn()).all(sql, params),
  run: async (sql, ...params) => (await conn()).run(sql, params),
  insert: async (sql, ...params) => (await conn()).insert(sql, params),
  exec: async (sql) => (await conn()).exec(sql),
  // A transaction; one already open is joined, not nested.
  tx: async (fn) => (als.getStore() ? fn() : (await open()).tx(fn)),
  ready: async () => (await open()).ready(),
  close: async () => { if (backend) await backend.close(); backend = null; opening = null; },
  // For the maintenance scripts that still need SQLite's own handle (better-sqlite3).
  sqliteHandle: async () => { const b = await open(); if (b.kind !== "sqlite") throw new Error("this script works on the SQLite file (STORAGE=sqlite)"); return b.raw; },
  // This interface over a better-sqlite3 handle a script opened itself (read-only, or a scratch copy),
  // for the library functions that take the database as an argument (lib/keystrokeSecurity.js).
  wrapSqlite: (h) => ({
    kind: "sqlite",
    get: async (sql, ...p) => h.prepare(sql).get(...p),
    all: async (sql, ...p) => h.prepare(sql).all(...p),
    run: async (sql, ...p) => ({ changes: h.prepare(sql).run(...p).changes }),
    insert: async (sql, ...p) => Number(h.prepare(sql).run(...p).lastInsertRowid),
  }),
  TABLES, toPg,
};

module.exports = db;
